"""Generate the intro wordmark paths from the bundled Yellowtail font.

Run from milo-app/:  /path/to/venv/bin/python scripts/build-wordmark.py
Needs fonttools and brotli (pip install fonttools brotli).

Writes src/intro/wordmark.generated.ts. Yellowtail is Apache-2.0 licensed;
see scripts/fonts/Yellowtail-LICENSE.txt.
"""

from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

WORD = "Milo"
ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "scripts" / "fonts" / "yellowtail-latin-400-normal.woff2"
OUT = ROOT / "src" / "intro" / "wordmark.generated.ts"
PADDING = 40  # font units of breathing room around the word


def main() -> None:
    font = TTFont(str(FONT))
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]

    # Pass 1: measure each glyph in font units, y-up.
    placed = []  # (char, glyph name, x offset in font units)
    x = 0
    for ch in WORD:
        name = cmap[ord(ch)]
        placed.append((ch, name, x))
        x += hmtx[name][0]

    # Pass 2: flip to SVG (y-down), place each letter, and collect bounds.
    letters = []
    bounds = [float("inf"), float("inf"), float("-inf"), float("-inf")]
    for ch, name, dx in placed:
        bp = BoundsPen(glyphs)
        glyphs[name].draw(TransformPen(bp, (1, 0, 0, 1, dx, 0)))
        if bp.bounds is None:
            continue
        xmin, ymin, xmax, ymax = bp.bounds
        bounds = [min(bounds[0], xmin), min(bounds[1], ymin), max(bounds[2], xmax), max(bounds[3], ymax)]
        letters.append((ch, name, dx))

    minx, miny, maxx, maxy = bounds
    view_x = minx - PADDING
    view_y = -maxy - PADDING  # y flips: SVG top is the font's maxY
    view_w = (maxx - minx) + 2 * PADDING
    view_h = (maxy - miny) + 2 * PADDING

    entries = []
    for ch, name, dx in letters:
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, dx, 0)))
        d = pen.getCommands()
        entries.append((ch, d))

    lines = [
        "// Generated by scripts/build-wordmark.py from scripts/fonts/yellowtail-latin-400-normal.woff2.",
        "// Do not edit by hand. Font: Yellowtail (Apache-2.0), see scripts/fonts/Yellowtail-LICENSE.txt.",
        "",
        f'export const WORDMARK_TEXT = "{WORD}";',
        f'export const WORDMARK_VIEWBOX = "{view_x:.1f} {view_y:.1f} {view_w:.1f} {view_h:.1f}";',
        "",
        "export const WORDMARK_LETTERS: readonly { char: string; d: string }[] = [",
    ]
    for ch, d in entries:
        lines.append(f'  {{ char: "{ch}", d: "{d}" }},')
    lines += ["];", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(entries)} letters, viewBox {view_x:.0f} {view_y:.0f} {view_w:.0f} {view_h:.0f}")


if __name__ == "__main__":
    main()
